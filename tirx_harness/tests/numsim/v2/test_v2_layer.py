"""The v2 Python layer (compile/run/report/api) over a hand-built Module.

The fixture ``fixtures/vector_add.module.json`` is generated by
``numsim-py``'s Rust test ``fixture_is_current`` from ``ProgramBuilder``, so
it always matches the ``numsim_core::Module`` contract. Execution tests skip
while the ``numsim-core`` scheduler bodies are still ``unimplemented!()``.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

FIXTURE = Path(__file__).parent / "fixtures" / "vector_add.module.json"

numsim_core_py = pytest.importorskip(
    "tirx_harness.numsim.v2.numsim_core_py",
    reason="numsim_core_py not built; run core-rs/numsim-py/build_dev.sh",
)

from tirx_harness.numsim import v2  # noqa: E402
from tirx_harness.numsim.v2 import report as rep  # noqa: E402


@pytest.fixture(scope="module")
def module():
    return v2.from_document(FIXTURE.read_bytes())


def _inputs():
    a = np.arange(1024, dtype=np.float32)
    b = np.full(1024, 0.5, dtype=np.float32)
    return {"a": a, "b": b, "c": np.zeros(1024, dtype=np.float32)}


def _skip_if_unimplemented(call):
    try:
        return call()
    except NotImplementedError as error:
        pytest.skip(f"numsim-core body not implemented yet: {error}")


# -- boundary ------------------------------------------------------------


def test_load_module_json_and_postcard(module):
    handle = module.handle
    assert handle.kernel_names == ["vadd"]
    assert handle.format_version == numsim_core_py.program_format_version()
    again = numsim_core_py.load_module(handle.to_bytes())
    assert json.loads(again.to_json()) == json.loads(handle.to_json())


def test_load_module_rejects_bad_documents():
    with pytest.raises(ValueError, match="format version"):
        numsim_core_py.load_module(json.dumps({"format_version": 999, "kernels": []}))
    with pytest.raises(v2.ModuleContractError):
        v2.from_document({"format_version": 1, "kernels": [{"name": "x"}]})


def test_native_run_rejects_unknown_mode_and_backend(module):
    with pytest.raises(ValueError, match="unknown mode"):
        numsim_core_py.run(module.handle, {}, mode="nope")
    with pytest.raises(ValueError, match="unknown backend"):
        numsim_core_py.run(module.handle, {}, backend="nope")


@pytest.mark.skipif(
    not __import__("os").environ.get("NUMSIM_V2_TEST_CODEGEN"),
    reason="codegen ABI follows the live rlib; set NUMSIM_V2_TEST_CODEGEN=1 after rebuilding",
)
def test_codegen_backend_matches_interpreter(module, tmp_path, monkeypatch):
    monkeypatch.setenv("NUMSIM_CACHE_DIR", str(tmp_path))
    inputs = _inputs()
    interp = _skip_if_unimplemented(lambda: v2.Engine(backend="interp").run(module, inputs))
    codegen = _skip_if_unimplemented(lambda: v2.Engine(backend="codegen").run(module, inputs))
    assert codegen.status == interp.status
    for name, value in interp.outputs.items():
        np.testing.assert_array_equal(codegen.outputs[name], value)


