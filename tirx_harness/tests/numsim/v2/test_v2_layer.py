def _core_finding(kind, status, site=0, start=0, length=4):
    return {
        "kind": kind,
        "status": status,
        "message": f"{kind} message",
        "sites": [site],
        "evidence": [
            {"role": "first_access", "site": site, "actor": None, "buffer": "c",
             "bytes": {"start": start, "len": length}, "detail": None},
            {"role": "second_access", "site": site, "actor": None, "buffer": "c",
             "bytes": {"start": start + 2, "len": length}, "detail": None},
        ],
    }


def test_phase_payload_from_core_findings(module):
    (kernel,) = module.spec.kernels
    span_of = kernel.source_span
    records = [
        rep.record_from_core(_core_finding("data_race", "Error"), span_of),
        rep.record_from_core(_core_finding("uninit_read", "Review"), span_of),
        rep.record_from_core(_core_finding({"other": "budget"}, "Incomplete"), span_of),
    ]
    payload = rep.phase_payload(
        checker="racecheck", phase_index=0, phase_name="vadd", records=records,
        status={"kind": "completed"}, diagnostics=[],
    )
    assert payload["verdict"] == "error"
    assert [r["kind"] for r in payload["findings"]] == ["data_race"]
    assert [r["kind"] for r in payload["advisories"]] == ["uninitialized_read"]
    assert [r["kind"] for r in payload["incomplete"]] == ["budget"]
    race = payload["findings"][0]
    assert race["overlaps"] == [{"byte_offset": 2, "byte_len": 2, "byte_end": 4}]
    span = race["sources"][0]["source_span"]
    assert span["kind"] == "span" and span["line"] == 10

    report = rep.RaceReport([rep.AnalysisResult("racecheck", payload)])
    assert report.verdict == "error"
    assert {f.kind for f in report.findings} == {"data_race", "uninitialized_read", "budget"}
    text = report.format()
    assert text.startswith("racecheck ERROR") and "data_race" in text
    with pytest.raises(AssertionError):
        report.require_clean()
    assert report.to_dict()["schema_version"] == 5


